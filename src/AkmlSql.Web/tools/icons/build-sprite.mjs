// Spec 041 (research R62) — builds the web edition's icon sprite from the vendored Lucide set.
//
// Reads the allow-list in icons.json, takes each icon's SVG from node_modules/lucide-static/icons,
// and writes one <symbol id="akml-icon-{name}"> per icon into wwwroot/lib/icons/akml-icons.svg,
// plus THIRD-PARTY-NOTICES.txt beside it. Shared/Icon.razor renders <use href="…#akml-icon-{name}">.
//
// Why a sprite (not a CDN, an icon font or inline C# strings): the web edition loads nothing from a
// CDN (on-prem / offline / strict CSP), an icon font needs @font-face and disappears in forced-colours
// mode, and inline SVG dictionaries in C# would bloat every render. Strokes are currentColor, so an
// icon takes the colour of the text around it in every theme.
//
// Run: npm ci && npm run build   (the generated files are committed, like the CodeMirror bundle).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(here, 'node_modules', 'lucide-static', 'icons');
const outDir = join(here, '..', '..', 'wwwroot', 'lib', 'icons');
const names = JSON.parse(readFileSync(join(here, 'icons.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(here, 'node_modules', 'lucide-static', 'package.json'), 'utf8'));

const seen = new Set();
const missing = [];
const symbols = [];
for (const name of names) {
    if (!/^[a-z0-9-]+$/.test(name)) throw new Error(`icons.json: invalid icon name '${name}'`);
    if (seen.has(name)) throw new Error(`icons.json: duplicate icon name '${name}'`);
    seen.add(name);

    let svg;
    try { svg = readFileSync(join(iconsDir, `${name}.svg`), 'utf8'); }
    catch { missing.push(name); continue; }

    // Keep only the drawing: everything between the root <svg …> tag and </svg>. Lucide sources
    // carry a licence comment and the root presentation attributes, which the <symbol> re-declares.
    const open = svg.indexOf('>', svg.indexOf('<svg'));
    const close = svg.lastIndexOf('</svg>');
    if (open < 0 || close < 0) throw new Error(`${name}.svg: unexpected file shape`);
    const body = svg.slice(open + 1, close)
        .replace(/<!--[\s\S]*?-->/g, '')
        .split('\n').map(l => l.trim()).filter(l => l.length > 0).join('');

    symbols.push(`  <symbol id="akml-icon-${name}" viewBox="0 0 24 24">${body}</symbol>`);
}
if (missing.length > 0) {
    throw new Error(`Not in lucide-static ${pkg.version}: ${missing.join(', ')}. Fix icons.json.`);
}

const sprite = [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- AKML SQL web edition icon sprite. GENERATED by src/AkmlSql.Web/tools/icons/build-sprite.mjs`,
    `     from lucide-static ${pkg.version} (ISC; see THIRD-PARTY-NOTICES.txt). Do not edit by hand. -->`,
    '<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2"',
    '     stroke-linecap="round" stroke-linejoin="round" style="display:none">',
    ...symbols,
    '</svg>',
    '',
].join('\n');

const licence = readFileSync(join(here, 'node_modules', 'lucide-static', 'LICENSE'), 'utf8').trim();
const notices = [
    'Third-party notices for wwwroot/lib/icons/akml-icons.svg',
    '',
    `The icons in akml-icons.svg are taken from Lucide (lucide-static ${pkg.version}),`,
    'https://lucide.dev, under the licence below: ISC, with the MIT licence covering the icons',
    'Lucide derives from the Feather project. Icons used:',
    '',
    ...names.map(n => `  ${n}`),
    '',
    '---',
    '',
    licence,
    '',
].join('\n');

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'akml-icons.svg'), sprite, 'utf8');
writeFileSync(join(outDir, 'THIRD-PARTY-NOTICES.txt'), notices, 'utf8');
console.log(`Wrote ${symbols.length} icons to ${join(outDir, 'akml-icons.svg')}`);
