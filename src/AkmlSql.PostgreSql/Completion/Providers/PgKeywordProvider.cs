using AkmlSql.Core.Ipc.Messages;
using AkmlSql.PostgreSql.Reference;

namespace AkmlSql.PostgreSql.Completion.Providers;

/// <summary>One source of completion items; the engine asks each in turn (spec 042 R4).</summary>
internal interface IPgCompletionProvider
{
    void Collect(PgCompletionInput input, List<CompletionItem> items);
}

/// <summary>
/// Spec 042 (task T100, FR-061) - key words and commands the grammar allows at the caret: the commands at the start of a
/// statement, the second word of a command, the clause words after a table or an expression, the continuations of
/// <c>IS</c>, <c>NULLS</c>, <c>GROUP</c>. The words are PostgreSQL's; nothing here is shared with the T-SQL keyword lists. A
/// word the reference dates after the connected server's release is not offered.
/// </summary>
internal sealed class PgKeywordProvider : IPgCompletionProvider
{
    private static readonly string[] ExprStart =
    {
        "CASE", "NOT", "EXISTS", "ARRAY", "ROW", "NULL", "TRUE", "FALSE", "CAST", "INTERVAL", "CURRENT_DATE", "CURRENT_TIMESTAMP",
        "CURRENT_TIME", "CURRENT_USER", "LOCALTIME", "LOCALTIMESTAMP",
    };

    private static readonly string[] ExprContinue =
    {
        "AND", "OR", "IS NULL", "IS NOT NULL", "IS DISTINCT FROM", "IS NOT DISTINCT FROM", "IN", "NOT IN", "LIKE", "NOT LIKE", "ILIKE",
        "NOT ILIKE", "BETWEEN", "NOT BETWEEN", "SIMILAR TO", "AT TIME ZONE", "COLLATE",
    };

    private static readonly string[] Joins =
    {
        "JOIN", "INNER JOIN", "LEFT JOIN", "LEFT OUTER JOIN", "RIGHT JOIN", "RIGHT OUTER JOIN", "FULL JOIN", "FULL OUTER JOIN",
        "CROSS JOIN", "NATURAL JOIN",
    };

    private static readonly string[] SetOps = { "UNION", "UNION ALL", "INTERSECT", "EXCEPT" };

    private static readonly string[] Tail = { "LIMIT", "OFFSET", "FETCH FIRST", "FOR UPDATE" };

    private static readonly string[] ColumnConstraints =
    {
        "NOT NULL", "NULL", "DEFAULT", "PRIMARY KEY", "UNIQUE", "CHECK", "REFERENCES", "GENERATED ALWAYS AS IDENTITY",
        "GENERATED BY DEFAULT AS IDENTITY", "GENERATED ALWAYS AS", "COLLATE", "CONSTRAINT",
    };

    private static readonly string[] TableConstraints = { "CONSTRAINT", "PRIMARY KEY", "UNIQUE", "CHECK", "FOREIGN KEY", "EXCLUDE", "LIKE" };

    private static readonly string[] AlterTableActions =
    {
        "ADD COLUMN", "ADD CONSTRAINT", "ADD PRIMARY KEY", "ADD FOREIGN KEY", "ADD UNIQUE", "ADD CHECK", "DROP COLUMN", "DROP CONSTRAINT",
        "ALTER COLUMN", "RENAME TO", "RENAME COLUMN", "RENAME CONSTRAINT", "OWNER TO", "SET SCHEMA", "SET TABLESPACE", "ENABLE ROW LEVEL SECURITY",
        "DISABLE ROW LEVEL SECURITY", "ATTACH PARTITION", "DETACH PARTITION", "SET LOGGED", "SET UNLOGGED",
    };

    private static readonly string[] AlterColumnActions =
    {
        "SET DATA TYPE", "TYPE", "SET DEFAULT", "DROP DEFAULT", "SET NOT NULL", "DROP NOT NULL", "ADD GENERATED", "DROP IDENTITY", "SET STATISTICS",
    };

    private static readonly string[] CreateExtras =
    {
        "OR REPLACE", "OR REPLACE VIEW", "OR REPLACE FUNCTION", "OR REPLACE PROCEDURE", "OR REPLACE TRIGGER", "UNIQUE INDEX", "TEMP TABLE",
        "TEMPORARY TABLE", "UNLOGGED TABLE", "RECURSIVE VIEW", "TEMP VIEW",
    };

    public void Collect(PgCompletionInput input, List<CompletionItem> items)
    {
        var c = input.Context;
        if (c.AfterDot || c.PrefixQuoted || !input.Options.IncludeKeywords) return;

        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var word in Words(c, input.Reference))
        {
            if (!seen.Add(word)) continue;
            if (!word.Contains(' ') && input.Reference.Keyword(word) is { } k && k.MinVersion > input.Options.ServerMajor) continue;
            items.Add(PgItems.Keyword_(word, Priority(c, word)));
        }
    }

    private static readonly HashSet<string> EverydayCommands = new(StringComparer.Ordinal)
    {
        "SELECT", "INSERT", "UPDATE", "DELETE", "WITH", "CREATE", "ALTER", "DROP", "TRUNCATE", "BEGIN", "COMMIT", "ROLLBACK", "EXPLAIN",
        "MERGE", "VALUES", "TABLE", "COPY", "GRANT", "REVOKE", "SET", "SHOW", "CALL", "DO", "VACUUM", "ANALYZE",
    };

    private static readonly HashSet<string> EverydayObjects = new(StringComparer.Ordinal)
    {
        "TABLE", "INDEX", "UNIQUE INDEX", "VIEW", "MATERIALIZED VIEW", "OR REPLACE VIEW", "OR REPLACE FUNCTION", "OR REPLACE PROCEDURE", "FUNCTION",
        "PROCEDURE", "SEQUENCE", "SCHEMA", "TYPE", "EXTENSION", "TRIGGER", "TEMP TABLE", "TEMPORARY TABLE", "UNLOGGED TABLE", "DATABASE", "ROLE",
    };

    // The words people reach for most come first, so they survive the suggestion cap.
    private static int Priority(PgCursorContext c, string word)
    {
        var last = c.PrecedingWords.Count > 0 ? c.PrecedingWords[^1] : string.Empty;
        if (last == "RETURNS" && word is "TABLE" or "SETOF" or "void" or "trigger") return PgItems.TypeName - 1;
        if (c.Clause is PgClause.None or PgClause.StatementStart)
            return EverydayCommands.Contains(word) ? PgItems.Keyword : PgItems.Keyword + 8;
        if (c.PrecedingWords.Count == 1 && last == c.Verb && last is "CREATE" or "ALTER" or "DROP")
            return EverydayObjects.Contains(word) ? PgItems.Keyword : PgItems.Keyword + 8;
        return word.Contains(' ') ? PgItems.CompoundKeyword : PgItems.Keyword;
    }

    private static List<string> Words(PgCursorContext c, PgReference reference)
    {
        var words = new List<string>();
        var last = c.PrecedingWords.Count > 0 ? c.PrecedingWords[^1] : string.Empty;
        var last2 = c.PrecedingWords.Count > 1 ? c.PrecedingWords[^2] : string.Empty;

        // Words that have a fixed continuation, wherever they appear.
        if (FixedContinuation(c, last, last2, words)) return words;

        var expression = c.AfterOperand ? ExprContinue : ExprStart;

        switch (c.Clause)
        {
            case PgClause.None:
            case PgClause.StatementStart:
                StatementStart(reference, words);
                break;

            case PgClause.With:
                if (c.AfterOperand && last == ")") words.AddRange(new[] { "SELECT", "INSERT", "UPDATE", "DELETE", "MERGE", "VALUES" });
                else if (c.AfterOperand) words.Add("AS");
                break;

            case PgClause.SelectList:
                if (!c.AfterOperand)
                {
                    if (last == "SELECT") words.AddRange(new[] { "DISTINCT", "DISTINCT ON", "ALL" });
                    words.AddRange(ExprStart);
                }
                else
                {
                    words.AddRange(new[] { "AS", "FROM", "INTO", "WHERE", "GROUP BY", "ORDER BY" });
                    words.AddRange(ExprContinue);
                    words.AddRange(SetOps);
                    words.AddRange(Tail);
                }
                break;

            case PgClause.From:
                if (!c.AfterOperand) words.AddRange(new[] { "LATERAL", "ONLY" });
                else
                {
                    words.AddRange(new[] { "AS", "TABLESAMPLE" });
                    words.AddRange(Joins);
                    words.AddRange(new[] { "WHERE", "GROUP BY", "ORDER BY", "WINDOW" });
                    words.AddRange(SetOps);
                    words.AddRange(Tail);
                }
                break;

            case PgClause.Join:
                if (!c.AfterOperand) words.AddRange(new[] { "LATERAL", "ONLY" });
                else words.AddRange(new[] { "AS", "ON", "USING" });
                break;

            case PgClause.JoinOn:
                words.AddRange(expression);
                if (c.AfterOperand)
                {
                    words.AddRange(Joins);
                    words.AddRange(new[] { "WHERE", "GROUP BY", "ORDER BY" });
                    words.AddRange(SetOps);
                    words.AddRange(Tail);
                }
                break;

            case PgClause.Where:
                words.AddRange(expression);
                if (c.AfterOperand)
                {
                    words.AddRange(new[] { "GROUP BY", "ORDER BY", "WINDOW", "RETURNING" });
                    words.AddRange(SetOps);
                    words.AddRange(Tail);
                }
                break;

            case PgClause.GroupBy:
                if (!c.AfterOperand) words.AddRange(new[] { "ROLLUP", "CUBE", "GROUPING SETS", "ALL", "DISTINCT" });
                else
                {
                    words.AddRange(new[] { "HAVING", "ORDER BY", "WINDOW" });
                    words.AddRange(SetOps);
                    words.AddRange(Tail);
                }
                break;

            case PgClause.Having:
                words.AddRange(expression);
                if (c.AfterOperand)
                {
                    words.AddRange(new[] { "ORDER BY", "WINDOW" });
                    words.AddRange(SetOps);
                    words.AddRange(Tail);
                }
                break;

            case PgClause.Window:
                if (c.AfterOperand) words.AddRange(new[] { "AS", "ORDER BY" });
                break;

            case PgClause.OrderBy when c.InWindowSpec:
                if (c.AfterOperand) words.AddRange(new[] { "ORDER BY", "ROWS", "RANGE", "GROUPS", "ASC", "DESC", "NULLS FIRST", "NULLS LAST" });
                else words.AddRange(new[] { "PARTITION BY", "ORDER BY" });
                break;

            case PgClause.OrderBy:
                if (c.AfterOperand) words.AddRange(new[] { "ASC", "DESC", "NULLS FIRST", "NULLS LAST", "USING", "LIMIT", "OFFSET", "FETCH FIRST", "FOR UPDATE" });
                else words.AddRange(ExprStart);
                break;

            case PgClause.Limit:
                if (!c.AfterOperand) words.Add("ALL");
                else words.AddRange(new[] { "OFFSET", "ROW", "ROWS", "ONLY", "WITH TIES" });
                break;

            case PgClause.SetOperation:
                words.AddRange(new[] { "ALL", "DISTINCT", "SELECT", "VALUES" });
                break;

            case PgClause.InsertTarget:
                if (c.AfterOperand) words.AddRange(new[] { "AS", "VALUES", "SELECT", "DEFAULT VALUES", "OVERRIDING SYSTEM VALUE", "OVERRIDING USER VALUE", "TABLE" });
                break;

            case PgClause.Values:
                if (!c.AfterOperand) words.AddRange(new[] { "DEFAULT" }.Concat(ExprStart));
                else words.AddRange(new[] { "ON CONFLICT", "RETURNING", "SELECT" });
                break;

            case PgClause.InsertColumns:
                break;

            case PgClause.OnConflictTarget:
                break;

            case PgClause.OnConflict:
                if (c.PrecedingWords.Count > 0 && last == "ON") words.Add("CONFLICT");
                else if (last == "CONFLICT") words.AddRange(new[] { "ON CONSTRAINT", "DO NOTHING", "DO UPDATE SET" });
                else words.AddRange(new[] { "WHERE", "DO NOTHING", "DO UPDATE SET" });
                break;

            case PgClause.OnConflictAction:
                if (last == "DO") words.AddRange(new[] { "NOTHING", "UPDATE SET" });
                else if (last == "UPDATE") words.Add("SET");
                break;

            case PgClause.Set:
                if (!c.AfterOperand) words.AddRange(new[] { "DEFAULT" }.Concat(ExprStart));
                else
                {
                    words.AddRange(ExprContinue);
                    words.AddRange(new[] { "WHERE", "FROM", "RETURNING" });
                }
                break;

            case PgClause.UpdateTarget:
                if (c.AfterOperand) words.AddRange(new[] { "AS", "SET" });
                break;

            case PgClause.DeleteTarget:
                if (c.AfterOperand) words.AddRange(new[] { "AS", "USING", "WHERE", "RETURNING" });
                break;

            case PgClause.Using:
                if (c.AfterOperand)
                {
                    words.AddRange(new[] { "AS", "WHERE", "RETURNING" });
                    words.AddRange(Joins);
                }
                break;

            case PgClause.Returning:
                if (!c.AfterOperand) words.AddRange(ExprStart);
                else words.AddRange(new[] { "AS" }.Concat(ExprContinue));
                break;

            case PgClause.MergeTarget:
                if (c.AfterOperand) words.AddRange(new[] { "AS", "USING" });
                break;

            case PgClause.MergeSource:
                if (c.AfterOperand) words.AddRange(new[] { "AS", "ON" });
                break;

            case PgClause.MergeWhen:
                if (last == "WHEN") words.AddRange(new[] { "MATCHED", "NOT MATCHED", "NOT MATCHED BY SOURCE", "NOT MATCHED BY TARGET" });
                else if (last == "MATCHED") words.AddRange(new[] { "AND", "THEN" });
                break;

            case PgClause.MergeAction:
                if (last == "THEN") words.AddRange(new[] { "UPDATE SET", "INSERT", "DELETE", "DO NOTHING" });
                break;

            case PgClause.DdlColumnName:
                if (c.InTableBody) words.AddRange(TableConstraints);
                break;

            case PgClause.DdlRelation:
                if (c.Verb is "DROP" or "TRUNCATE" && last is "TABLE" or "DROP" or "VIEW" or "INDEX" or "SEQUENCE" or "TRUNCATE")
                    words.Add(c.Verb == "DROP" ? "IF EXISTS" : "ONLY");
                break;

            case PgClause.Other:
                Other(c, last, reference, words);
                break;
        }

        return words;
    }

    private static void StatementStart(PgReference reference, List<string> words)
    {
        foreach (var command in reference.AllCommands)
        {
            var first = command.Name.Split(' ', 2)[0];
            if (!words.Contains(first)) words.Add(first);
        }
    }

    // Verbs and clause words not covered by a clause of their own.
    private static void Other(PgCursorContext c, string last, PgReference reference, List<string> words)
    {
        if (c.InTableBody)
        {
            if (c.AfterOperand || c.PrecedingWords.Count > 1) words.AddRange(ColumnConstraints);
            return;
        }

        switch (c.Verb)
        {
            case "INSERT":
                if (last == "INSERT") words.Add("INTO");
                else if (c.AfterOperand) words.AddRange(new[] { "VALUES", "SELECT", "DEFAULT VALUES", "OVERRIDING SYSTEM VALUE", "OVERRIDING USER VALUE", "TABLE" });
                break;
            case "DELETE":
                if (last == "DELETE") words.Add("FROM");
                break;
            case "UPDATE":
                break;
            case "CREATE":
                if (last == "CREATE") { SecondWords(reference, "CREATE", words); words.AddRange(CreateExtras); }
                else if (last == "USING" && c.DdlObject == "INDEX") words.AddRange(new[] { "btree", "hash", "gist", "spgist", "gin", "brin" });
                else if (c.DdlObject == "TABLE" && c.AfterOperand) words.AddRange(new[] { "AS", "PARTITION BY", "PARTITION OF", "INHERITS", "TABLESPACE", "WITH" });
                else if (c.DdlObject is "VIEW" && c.AfterOperand) words.AddRange(new[] { "AS" });
                else if (c.DdlObject == "INDEX" && c.AfterOperand) words.AddRange(new[] { "ON", "USING", "WHERE", "INCLUDE" });
                else if (c.DdlObject is "FUNCTION" or "PROCEDURE" && c.AfterOperand) words.AddRange(new[] { "RETURNS", "LANGUAGE", "AS", "VOLATILE", "STABLE", "IMMUTABLE", "STRICT", "SECURITY DEFINER" });
                break;
            case "ALTER":
                if (last == "ALTER") SecondWords(reference, "ALTER", words);
                else if (c.AfterOperand && c.PrecedingWords.Count > 2 && c.PrecedingWords[^2] == "COLUMN" && c.PrecedingWords[^3] == "ALTER") words.AddRange(AlterColumnActions);
                else if (c.DdlObject == "TABLE" && c.AfterOperand) words.AddRange(AlterTableActions);
                break;
            case "DROP":
                if (last == "DROP") SecondWords(reference, "DROP", words);
                else if (c.AfterOperand) words.AddRange(new[] { "CASCADE", "RESTRICT" });
                break;
            case "TRUNCATE":
                if (c.AfterOperand) words.AddRange(new[] { "RESTART IDENTITY", "CONTINUE IDENTITY", "CASCADE", "RESTRICT" });
                break;
            case "COMMENT":
                if (last == "COMMENT") words.Add("ON");
                else if (last == "ON") words.AddRange(new[] { "TABLE", "COLUMN", "VIEW", "INDEX", "FUNCTION", "SCHEMA", "SEQUENCE" });
                break;
            case "EXPLAIN":
                break;
            default:
                // Any other verb: its second word, when the reference has commands that begin with it.
                if (c.PrecedingWords.Count == 1 && last == c.Verb) SecondWords(reference, c.Verb, words);
                break;
        }
    }

    // CREATE TABLE, CREATE INDEX, ... -> TABLE, INDEX, ... (the words after the first, from the reference)
    private static void SecondWords(PgReference reference, string first, List<string> words)
    {
        foreach (var command in reference.CommandsStartingWith(first))
        {
            var rest = command.Name.Length > first.Length ? command.Name.Substring(first.Length).Trim() : string.Empty;
            if (rest.Length > 0 && !words.Contains(rest)) words.Add(rest);
        }
    }

    // Words with one fixed continuation. Returns true when the continuation is the whole answer.
    /// <summary>True when the word before the caret allows only a few key words next (IS, GROUP, LEFT, NULLS, ...): the answer is those words alone.</summary>
    public static bool IsFixedContinuation(PgCursorContext c)
    {
        var last = c.PrecedingWords.Count > 0 ? c.PrecedingWords[^1] : string.Empty;
        var last2 = c.PrecedingWords.Count > 1 ? c.PrecedingWords[^2] : string.Empty;
        return FixedContinuation(c, last, last2, new List<string>());
    }

    // Words that start an operand, so a NOT right after them is a prefix operator (WHERE NOT active), not the infix of NOT IN.
    private static readonly HashSet<string> OperandStarts = new(StringComparer.Ordinal)
    {
        "", "WHERE", "AND", "OR", "ON", "HAVING", "WHEN", "THEN", "ELSE", "SELECT", "(", ",", "=", "<", ">", "<>", "!=", "<=", ">=", "||",
        "+", "-", "*", "/", "CASE", "BY", "NOT", "SET", "VALUES", "RETURNING", "DISTINCT", "ALL",
    };

    private static bool FixedContinuation(PgCursorContext c, string last, string last2, List<string> words)
    {
        switch (last)
        {
            case "IS":
                words.AddRange(new[] { "NULL", "NOT NULL", "TRUE", "FALSE", "UNKNOWN", "DISTINCT FROM", "NOT DISTINCT FROM" });
                return true;
            case "NOT" when last2 == "IS":
                words.AddRange(new[] { "NULL", "TRUE", "FALSE", "UNKNOWN", "DISTINCT FROM" });
                return true;
            case "WHEN" when c.Clause == PgClause.MergeWhen:
                words.AddRange(new[] { "MATCHED", "NOT MATCHED", "NOT MATCHED BY SOURCE", "NOT MATCHED BY TARGET" });
                return true;
            case "THEN" when c.Clause == PgClause.MergeAction:
                words.AddRange(new[] { "UPDATE SET", "INSERT", "DELETE", "DO NOTHING" });
                return true;
            case "NOT" when c.Clause == PgClause.With:
                words.Add("MATERIALIZED");
                return true;
            case "NOT" when c.Clause is PgClause.DdlColumnType or PgClause.Other && c.InTableBody:
                words.Add("NULL");
                return true;
            case "NOT" when c.Clause == PgClause.MergeWhen:
                words.AddRange(new[] { "MATCHED", "MATCHED BY SOURCE", "MATCHED BY TARGET" });
                return true;
            case "NOT" when c.Clause is not (PgClause.DdlColumnName or PgClause.DdlColumnType) && !OperandStarts.Contains(last2):
                words.AddRange(new[] { "IN", "LIKE", "ILIKE", "BETWEEN", "SIMILAR TO" });
                return true;
            case "AS" when c.Clause == PgClause.With:
                words.AddRange(new[] { "MATERIALIZED", "NOT MATERIALIZED" });
                return true;
            case "WITH" when c.Clause == PgClause.With:
                words.Add("RECURSIVE");
                return true;
            case "NULLS":
                words.AddRange(new[] { "FIRST", "LAST" });
                return true;
            case "GROUP" or "ORDER" or "PARTITION":
                words.Add("BY");
                return true;
            case "LEFT" or "RIGHT" or "FULL":
                words.AddRange(new[] { "JOIN", "OUTER JOIN" });
                return true;
            case "INNER" or "CROSS" or "OUTER":
                words.Add("JOIN");
                return true;
            case "NATURAL":
                words.AddRange(new[] { "JOIN", "INNER JOIN", "LEFT JOIN", "RIGHT JOIN", "FULL JOIN" });
                return true;
            case "FETCH":
                words.AddRange(new[] { "FIRST", "NEXT" });
                return true;
            case "FOR" when c.Clause is not (PgClause.DdlColumnName or PgClause.DdlColumnType):
                words.AddRange(new[] { "UPDATE", "NO KEY UPDATE", "SHARE", "KEY SHARE" });
                return true;
            case "PRIMARY" or "FOREIGN":
                words.Add("KEY");
                return true;
            case "GENERATED":
                words.AddRange(new[] { "ALWAYS AS IDENTITY", "BY DEFAULT AS IDENTITY", "ALWAYS AS" });
                return true;
            case "DELETE" or "UPDATE" when last2 == "ON":
                words.AddRange(new[] { "CASCADE", "SET NULL", "SET DEFAULT", "RESTRICT", "NO ACTION" });
                return true;
            case "OVERRIDING":
                words.AddRange(new[] { "SYSTEM VALUE", "USER VALUE" });
                return true;
            case "DEFAULT" when c.Clause == PgClause.InsertTarget || c.Verb == "INSERT":
                words.Add("VALUES");
                return true;
            case "RETURNS":
                words.AddRange(new[] { "TABLE", "SETOF", "void", "trigger" });
                return false;
        }
        return false;
    }
}
