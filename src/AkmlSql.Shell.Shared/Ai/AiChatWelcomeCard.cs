#nullable enable
using System;
using System.Collections.Generic;
using System.Windows;
using System.Windows.Automation;
using System.Windows.Controls;
using AkmlSql.Shell.Shared.Ui.Theme;

namespace AkmlSql.Shell.Shared.Ai
{
    /// <summary>
    /// Spec 046 (US2, FR-023, contracts/chat-rendering.md Part 4, research R7): what an empty
    /// conversation shows while an agent can answer — the database the chat is bound to, the agent
    /// that answers, what the chat can do, and three starter questions that send on a click, the
    /// way Copilot Chat opens. Replaces spec 037's greeting bubble; the no-agent onboarding card
    /// (<see cref="AiChatEmptyState"/>) is unchanged. Theme tokens only, hoisted fonts.
    /// </summary>
    internal sealed class AiChatWelcomeCard : UserControl
    {
        /// <summary>Accessible name of the card's title line.</summary>
        internal const string TitleAutomationName = "Chat welcome";

        /// <summary>Accessible name of the line naming the answering agent.</summary>
        internal const string AgentAutomationName = "Chat welcome agent";

        internal const string StarterToolTip = "Send this question";

        internal const string NotBoundTitle = "Not connected to a database";

        internal const string Description =
            "Answers use the schema of the query window's database. SQL in answers can be inserted into the query window.";

        /// <summary>The three starters, in order (generic database questions — none is generated by the AI).</summary>
        internal static readonly IReadOnlyList<string> StarterQuestions = new[]
        {
            "What are the largest tables in this database?",
            "Which tables have no primary key?",
            "Which stored procedures were modified most recently?"
        };

        private readonly TextBlock _title;
        private readonly TextBlock _agent;
        private readonly List<Button> _starters = new List<Button>();

        /// <summary>Raised with the starter's text when the user picks one.</summary>
        public event EventHandler<string>? StarterRequested;

        public AiChatWelcomeCard()
        {
            _title = new TextBlock
            {
                Text = NotBoundTitle,
                FontFamily = Typography.UiFont,
                FontSize = Typography.BodyStrong,
                FontWeight = Typography.WeightSemiBold,
                TextWrapping = TextWrapping.Wrap
            };
            _title.SetResourceReference(TextBlock.ForegroundProperty, ThemeTokens.TextPrimary);
            AutomationProperties.SetName(_title, TitleAutomationName);

            _agent = new TextBlock
            {
                FontFamily = Typography.UiFont,
                FontSize = Typography.Small,
                TextWrapping = TextWrapping.Wrap,
                Margin = new Thickness(0, 2, 0, 0),
                Visibility = Visibility.Collapsed
            };
            _agent.SetResourceReference(TextBlock.ForegroundProperty, ThemeTokens.TextSecondary);
            AutomationProperties.SetName(_agent, AgentAutomationName);

            var description = new TextBlock
            {
                Text = Description,
                FontFamily = Typography.UiFont,
                FontSize = Typography.Body,
                TextWrapping = TextWrapping.Wrap,
                Margin = new Thickness(0, Spacing.Sm, 0, Spacing.Sm)
            };
            description.SetResourceReference(TextBlock.ForegroundProperty, ThemeTokens.TextSecondary);

            var stack = new StackPanel { Orientation = Orientation.Vertical };
            stack.Children.Add(_title);
            stack.Children.Add(_agent);
            stack.Children.Add(description);

            foreach (var question in StarterQuestions)
            {
                var starter = new Button
                {
                    Content = question,
                    ToolTip = StarterToolTip,
                    HorizontalAlignment = HorizontalAlignment.Left,
                    HorizontalContentAlignment = HorizontalAlignment.Left,
                    Padding = new Thickness(Spacing.Sm, Spacing.Xs, Spacing.Sm, Spacing.Xs),
                    Margin = new Thickness(0, 0, 0, Spacing.Xs),
                    FontSize = Typography.Small,
                    BorderThickness = new Thickness(1),
                    Cursor = System.Windows.Input.Cursors.Hand,
                    FocusVisualStyle = FocusVisualStyles.HighStakes
                };
                starter.SetResourceReference(Button.BackgroundProperty, ThemeTokens.SurfacePanel);
                starter.SetResourceReference(Button.ForegroundProperty, ThemeTokens.TextLink);
                starter.SetResourceReference(Button.BorderBrushProperty, ThemeTokens.BorderDefault);
                AutomationProperties.SetName(starter, question);
                ToolTipService.SetShowOnDisabled(starter, true);   // the busy state explains itself
                var text = question;
                starter.Click += (_, _) => StarterRequested?.Invoke(this, text);
                _starters.Add(starter);
                stack.Children.Add(starter);
            }

            var card = new Border
            {
                Child = stack,
                Padding = new Thickness(Spacing.Md),
                Margin = new Thickness(Spacing.Sm, Spacing.Sm, Spacing.Sm, Spacing.Sm),
                CornerRadius = new CornerRadius(Spacing.Sm),
                BorderThickness = new Thickness(1)
            };
            card.SetResourceReference(Border.BackgroundProperty, ThemeTokens.SurfaceElevated);
            card.SetResourceReference(Border.BorderBrushProperty, ThemeTokens.BorderDefault);

            Content = card;
        }

        /// <summary>The title names the bound database, or says there is none.</summary>
        internal void SetBinding(ChatBinding binding)
            => _title.Text = binding.State == ChatBindingState.Bound
                ? $"Ask about {binding.Server}.{binding.Database}"
                : NotBoundTitle;

        /// <summary>Names the agent that will answer ("Answers come from …"); hidden when unknown.</summary>
        internal void SetAgent(string? agentLabel)
        {
            if (string.IsNullOrWhiteSpace(agentLabel))
            {
                _agent.Visibility = Visibility.Collapsed;
                return;
            }
            _agent.Text = $"Answers come from {agentLabel}.";
            _agent.Visibility = Visibility.Visible;
        }

        /// <summary>While an answer is in flight the starters do nothing (and say why).</summary>
        internal bool IsBusy
        {
            set
            {
                foreach (var starter in _starters)
                {
                    starter.IsEnabled = !value;
                    starter.ToolTip = value ? "Wait for the answer to finish" : StarterToolTip;
                }
            }
        }

        /// <summary>The current title text (tests and the accessibility pass read it).</summary>
        internal string TitleText => _title.Text;

        /// <summary>The current agent line ("" when hidden).</summary>
        internal string AgentText => _agent.Visibility == Visibility.Visible ? _agent.Text : string.Empty;
    }
}
